#!/usr/bin/env python3
"""Validate the Render Blueprint's critical topology and safe defaults."""
from pathlib import Path
import sys
import yaml

root = Path(__file__).resolve().parents[1]
blueprint = yaml.safe_load((root / "render.yaml").read_text())
services = {item["name"]: item for item in blueprint.get("services", [])}
databases = {item["name"]: item for item in blueprint.get("databases", [])}
errors: list[str] = []

for required in ("imperionx-api", "imperionx-frontend"):
    if required not in services:
        errors.append(f"missing service: {required}")
if "imperionx-db" not in databases:
    errors.append("missing managed PostgreSQL database")

api = services.get("imperionx-api", {})
api_vars = {item.get("key"): item for item in api.get("envVars", []) if isinstance(item, dict)}
if api.get("healthCheckPath") != "/ready":
    errors.append("API health check must use /ready")
if api.get("preDeployCommand") != "alembic upgrade head":
    errors.append("API must run Alembic migrations before deployment")
if api_vars.get("WEBHOOK_DELIVERY_ENABLED", {}).get("value") != "false":
    errors.append("outbound webhook delivery must remain disabled by default")
if api_vars.get("DATABASE_URL", {}).get("fromDatabase", {}).get("name") != "imperionx-db":
    errors.append("API must use the managed private PostgreSQL database")
if api_vars.get("MFA_ENCRYPTION_KEY", {}).get("generateValue") is not True:
    errors.append("MFA encryption key must be generated by the host")
if api_vars.get("PUBLIC_RATE_LIMIT_HMAC_KEY", {}).get("generateValue") is not True:
    errors.append("rate-limit HMAC key must be generated by the host")

front = services.get("imperionx-frontend", {})
front_vars = {item.get("key"): item for item in front.get("envVars", []) if isinstance(item, dict)}
if front_vars.get("IMPERIONX_API_INTERNAL", {}).get("fromService", {}).get("name") != "imperionx-api":
    errors.append("frontend must proxy through the private API service")

for name, service in services.items():
    if service.get("autoDeployTrigger") != "checksPass":
        errors.append(f"{name} must deploy only after CI checks pass")
    if service.get("region") != "frankfurt":
        errors.append(f"{name} must share the Frankfurt region with PostgreSQL")
if databases.get("imperionx-db", {}).get("ipAllowList") != []:
    errors.append("database must not allow public IP connections")

if errors:
    print("Render Blueprint validation failed:", file=sys.stderr)
    for error in errors:
        print(f" - {error}", file=sys.stderr)
    raise SystemExit(1)
print("PASS: Render Blueprint topology, CI gates, private database and safe webhook defaults")
